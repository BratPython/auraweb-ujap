// Interpola linealmente entre dos arrays de puntos
export function lerpPoints(fromPts, toPts, t) {
  return fromPts.map((pt, i) => {
    const tp = toPts[i] || pt;
    return [pt[0] + (tp[0] - pt[0]) * t, pt[1] + (tp[1] - pt[1]) * t];
  });
}
